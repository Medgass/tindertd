export function getStudentsByTD(td: string): DatabaseStudent[] {
  return studentsDatabase.filter(student => student.td === td);
}

export function findStudentByCIN(cin: string): DatabaseStudent | undefined {
  return studentsDatabase.find(student => student.cin === cin);
}

export function getAllTDs(): string[] {
  return Array.from(new Set(studentsDatabase.map(student => student.td))).sort();
}

export function searchStudents(query: string): DatabaseStudent[] {
  const normalizedQuery = query.toLowerCase().trim();
  if (!normalizedQuery) return [];
  
  return studentsDatabase.filter(student => 
    student.nom.toLowerCase().includes(normalizedQuery) ||
    student.prenom.toLowerCase().includes(normalizedQuery) ||
    student.cin.includes(normalizedQuery)
  ).slice(0, 10); // Limite à 10 résultats
}